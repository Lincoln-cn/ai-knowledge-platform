-- ════════════════════════════════════════════════════════════════════════════
-- 登录失败计数与锁定（等保 · 三级要求）
-- ════════════════════════════════════════════════════════════════════════════
--
-- 等保对"身份鉴别"的要求里有一条：应对登录失败做出处理 —— 限制连续失败次数，
-- 并在超限后冻结该账号一段时间。本项目取 **连续失败 3 次 ⇒ 锁定 30 分钟**
-- （阈值与时长可配：app.security.login-failure.*）。
--
-- ★ 为什么落库、而不是放在内存里（例如一个 Caffeine 计数器）：
--   "锁定"是一个**安全状态**，它必须能跨进程重启存活。放内存的话，
--   重启一次就等于给了攻击者一轮全新的 3 次机会 —— 而重启恰恰是运维的日常动作。
--   对照组：验证码放内存是**可以**的，因为它 2 分钟就过期，重启丢掉的代价几乎为零。
--   判断标准是"它是否承载一个需要跨越重启的约束"。
--
-- ★ 为什么锁定字段放在 iam_user 上、而不是单开一张 iam_login_attempt 表：
--   这两列是"这个账号当前的鉴别状态"，与账号是 1:1 的，且需要在同一事务里
--   与密码校验结果一起更新。单开表会引入一次额外的写和一张要清理的表
--   （失败记录会无限堆积）。真要做"登录审计"（谁在什么时候从哪里试过）时，
--   那是**另一件事**——审计表记的是历史事实，而不是当前状态。
-- ════════════════════════════════════════════════════════════════════════════

alter table iam_user
  add column failed_login_attempts integer not null default 0,
  add column locked_until          timestamptz;

comment on column iam_user.failed_login_attempts is
  '连续登录失败次数。达到阈值时置 0 并写 locked_until —— 解锁后重新计数';
comment on column iam_user.locked_until is
  '锁定截止时刻。null 或已过期表示未锁定';
