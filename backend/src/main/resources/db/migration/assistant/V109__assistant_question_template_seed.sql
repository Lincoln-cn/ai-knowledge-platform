-- 12 条通用提问模板（kind = 'QUESTION'）。
--
-- ★ 它们解决的是「用户不知道该问什么」，不是「配置者写不清要求」——
--   后者是 as_prompt_config 里 kind = 'ROLE' 的那批（V106）。
--
-- ★ 幂等：靠 role_name 判重（与应用引用无关，模板是全局资产）。
--
-- ★ 正文里的 {花括号} 是可替换的占位内容：对话页把它渲染成可编辑的小块，
--   用户不改就直接用里面的默认文字。

insert into as_prompt_config (id, kind, role_name, call_word, type_id, description, icon, app_id, created_at, updated_at)
select gen_random_uuid(), 'QUESTION', v.role_name, v.call_word, t.id, v.description, v.icon, null, now(), now()
from (values
  ('合同风险快速体检', '这份合同里有没有对我方不利的条款？',
   '先看风险，再看条款是否可谈', '🧭', '合同法务'),
  ('付款与违约摘出来', '帮我把这份合同的付款节点和违约责任摘出来',
   '只取这两类信息，别的不要', '💰', '合同法务'),
  ('单条条款风险评估', '{条款} 这条如果是对方起草的，常见风险是什么？',
   '拿单条去问，比通读整份更快', '⚖️', '合同法务'),
  ('事项怎么规定的', '{事项} 是怎么规定的？',
   '最常用的一句：把事项填进去', '📋', '制度咨询'),
  ('出差住宿标准', '出差住宿标准是多少？',
   '带数字的制度问题，答案要能追到条款', '🧾', '制度咨询'),
  ('两份制度冲突', '这两份制度的说法不一致，按哪个执行？',
   '让模型先列事实再判断', '🔀', '制度咨询'),
  ('我的情况适用哪条', '我这种情况适用哪条规定？',
   '把情形描述清楚再问', '🙋', '制度咨询'),
  ('整理成三条要点', '把这份文档整理成三条要点',
   '长文速读的默认动作', '✂️', '写作辅助'),
  ('改成公文语气', '把下面这段改成正式的公文语气',
   '保持原意，只改表达', '🖋️', '写作辅助'),
  ('按会议纪要格式整理', '按会议纪要的格式整理：一、结论 二、待办 三、分歧',
   '结构定死，模型不会漏项', '📝', '写作辅助'),
  ('这份资料讲了什么', '这份资料主要讲了什么？',
   '上传文档后的第一问', '📖', '通用'),
  ('术语一句话解释', '{术语} 是什么意思，用一句话解释',
   '术语查询的最短问法', '💡', '通用')
) as v(role_name, call_word, description, icon, type_name)
join as_prompt_type t on t.type_name = v.type_name
where not exists (
  select 1 from as_prompt_config c
  where c.kind = 'QUESTION' and c.role_name = v.role_name
);
