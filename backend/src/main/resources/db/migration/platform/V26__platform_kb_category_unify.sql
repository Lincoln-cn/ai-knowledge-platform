-- ════════════════════════════════════════════════════════════════════════════
-- 把「库分类」统一到字典一个真源（用户 2026-10-08 报的不一致）
-- ════════════════════════════════════════════════════════════════════════════
--
-- 现象（开发库实测）：
--   库里实际：制度规范 15 · 合同 2 · 产品资料 1 · 其他 1
--   字典里：  制度规范 · 产品资料 · 行业标准
-- ⇒ **两个真源**：建库下拉从字典取、列表筛选从"已有数据的去重"取，于是
--   「筛选里能看到『合同』，建库时却选不到」——正是用户报的那种不一致。
--
-- 处置（两半，缺一不可）：
--   ① 把字典补成"能表达既有数据"的清单（**加**而不是删：字典的纪律是只停用不删除，
--      而删掉一个 code 会让历史数据的展示回落成机器码）；
--   ② 顺手把**语义就不该在那儿的取值**归位：`合同` 是**文种**的词汇（`doc_type`），
--      不是库分类 —— 它出现在 `kb_category` 里是早先夹具留下的错值。
--
-- ★ 为什么这一步必须做，而不是"让筛选继续自己统计"：那样两个来源迟早再漂一次，
--   而症状永远是"界面上少了一个选项"这种静默的不一致（本项目最贵的病）。
-- ════════════════════════════════════════════════════════════════════════════

-- ② 先把错值归位（放在加新值之前：避免"合同"这个 code 被当成合法分类留下来）
update kb_knowledge_base
   set category = '其他', updated_at = now()
 where category = '合同';

-- ① 把既有数据的取值补进字典（"其他"是合理的兜底分类；行业标准本来就在字典里）
insert into platform_dict_item (id, kind, code, label, sort, enabled, remark, created_at, updated_at)
values
  (gen_random_uuid(), 'KB_CATEGORY', '其他', '其他', 9, true,
   '兜底分类。★ 出现它说明有人没选分类就建库（接口上 category 必填，所以它主要来自历史/夹具数据）',
   now(), now())
on conflict (kind, code) do nothing;
