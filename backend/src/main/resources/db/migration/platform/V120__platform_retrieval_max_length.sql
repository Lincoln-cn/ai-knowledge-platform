-- ════════════════════════════════════════════════════════════════════════════
-- platform 模块：重排的截断长度进「检索引擎配置」页（0.9.9）
-- ════════════════════════════════════════════════════════════════════════════
--
-- 契约：`pf_retrieval_settings` 多一列 `rerank_max_length`，随之
--       `GET|PUT /retrieval/settings` 的 `RetrievalEngineSettings` 多一个字段。
--
-- ★★ 为什么这一格也要落库，而不是留在 `application.yml`：
--   它是重排耗时上最直接的旋钮 —— 分段计时实测重排占一条问句的 45~62%
--   （`93eeb9d9`：6361ms / 11250ms），而重排的耗时几乎全在 cross-encoder 的 token
--   前向上。2026-11-28 实测同一条问句：截断 512 → 256 让重排从 **6595ms 降到 4389ms**
--   （−33%），合计 **10096ms → 8482ms**（−16%）。
--   一个能把 B4 从"贴着 10s 门槛"改到"有 1.5s 余量"的旋钮，如果只能改环境变量重启
--   才能试，那它和 `V100` 里那四格是同一种问题 —— 而 `V100` 的文件头已经把那条纪律
--   写死了：**凡是界面上能开、读数能看到的策略开关，都必须在持久化的检索参数里有格子**。
--
-- ★ 为什么范围是 32..2048 而不是 1..2048：
--   32 个 token 大致只够一个短标题，再短就等于"把整段话截成一个词"，重排分数会退化成
--   噪声 —— 那种值不应该能被填进去。2048 是 bge-reranker-base 的可用上限附近，
--   再大也加不动多少效果，只会把单条延迟推到几十秒。
--
-- ★ 与 `V100` 的默认值保持一字不差：
--   `application.yml` 的 `app.retrieval.rerank.max-length` 默认 512，库里也 512。
--   两边不一致的症状是"演示时好用、部署后行为不同"（同 `V20` 的理由）。
-- ════════════════════════════════════════════════════════════════════════════

alter table pf_retrieval_settings
  add column rerank_max_length integer not null default 512
    check (rerank_max_length between 32 and 2048);

comment on column pf_retrieval_settings.rerank_max_length is
  '重排的截断长度（token）。512→256 实测重排 −33%、合计 −16%（2026-11-28）；截断越短长条文的尾巴越容易被砍掉，改它必须重跑语料对照 B3。';
