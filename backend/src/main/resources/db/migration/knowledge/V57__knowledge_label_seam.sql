-- knowledge 模块：kb_document.labels / kb_segment.labels（密级标签，正交维度）
-- —— Issue `#26` 的第一刀（`13 §1.1` / `13 §8.3` 的 M2 验收项）
-- ════════════════════════════════════════════════════════════════════════════
--
-- ★ 标签不是「更细的密级」。`13 §1.1` 的口径是两条**正交**的轴：
--   · 等级链（PUBLIC < INTERNAL < SECRET < CONFIDENTIAL）是**偏序格**，比出来的是「不高于」；
--   · 标签（"财务资料" / "人事资料"）是**集合**，比出来的是「相交」。
--   把它们合成一个数字或一个字符串的后果，是「内部 · 财务资料」这份文档在
--   「机密」这个角色面前变成看得见（因为机密 > 内部），而那是一次**静默越权**。
--
-- ★ 为什么现在加列（而不是等真正要用标签时）：
--   `13 §6.3` 第 2/3 项把它列为最贵的两处耦合点之一 ——「后加容易，
--   但『当年那份文档该打什么标签』要人去回忆」。标签是**人工填写**的信息，
--   不是算出来的：文档还在的时候补，是补一次；量产几十万分段之后再补，是补一个不可能。
--   同理 `#75` 的留存期、`#86` 的版本号，都是「列先到、语义后到」。
--
-- ★ 今天这一步做到哪、没做到哪（判据写在 Issue 里，别把它读成"标签功能已完成"）：
--   · 已做：两列 + 检索谓词按**交集**过滤（`JdbcSegmentSearchQuery.LABEL_PREDICATE`）
--     —— 语义先接上，数据后填：等将来有人开始写标签时，过滤已经生效，不会出现
--     "写了标签但没人按它过滤"的空窗期（那是本项目最贵的病：`#40` / `#160` / `#228`）。
--   · 没做：建档/编辑时填标签的入口、分段继承的执行点、一致性巡检的告警。
--     今天两列恒为 NULL ⇒ 谓词恒真 ⇒ **行为零变化**，这一点由
--     `SegmentLabelFilterTest` 与它的反证一起钉住。
--
-- ★ 语义三条（与 `ScopeFilter.canSeeClassification` 逐字对齐，两处不许各写一份）：
--   ① 我的标签集**为空** ⇒ 不按标签限制（这是绝大多数角色的状态；
--      若写成"必须相交"，没配标签的人会看不到任何东西）；
--   ② 文档标签**为空** ⇒ 谁都能看（标签是可选的，没打标签不是"绝密"）；
--   ③ 两边都非空 ⇒ **相交才可见**。
-- ════════════════════════════════════════════════════════════════════════════

alter table kb_document
  add column labels text[];

alter table kb_segment
  add column labels text[];

comment on column kb_document.labels is
  '密级标签（正交于 classification，13 §1.1）。NULL 或空数组 = 不受标签限制；'
  '语义与 ScopeFilter.canSeeClassification 逐字对齐，两份口径不许各写一份（#26）';

comment on column kb_segment.labels is
  '冗余的密级标签（继承文档，与 classification 同一套传播规则）。'
  '冗余的理由与 classification 完全相同：谓词必须能在 kb_segment 上直接生效，'
  '否则「两路同谓词」退化成「两处 join 写法必须一致」。★ 今天仍为 NULL（#26 只落了列与谓词）';

-- 交集（&&）走 GIN；标签是数组的精确元素匹配，不需要 pg_trgm
create index idx_kb_segment_labels on kb_segment using gin (labels);
