-- knowledge 模块：**删掉 `kb_knowledge_base` 的四个只写不读的计数列**
--   （`document_count` / `segment_count` / `char_count` / `has_vectorized_content`）
-- 2026-10-29 · Issue #44 / 出处 #35 + PR #36 / `ROADMAP §11.10.32`
-- ════════════════════════════════════════════════════════════════════════════
--
-- ── 为什么是 V54 而不是别的号 ────────────────────────────────────────────────
--
-- ★ Flyway 的 `locations: classpath:db/migration` 是**单一版本号链**（不按模块目录分段），
--   既有链末 = `conversation/V53`（PR #234 那批），所以本迁移的下一号是 **54**。
-- ★ 不许改 `V12` / `V900` 之外的任何既有迁移（checksum 就变了、后端起不来）；
--   `V12` 是历史（它建了这四列），本文件只负责**后续的删除**，两处不冲突。
--
-- ── 为什么删（三件取证，取自 Issue #44 与 #35 的实测）─────────────────────────
--
--   ① **读侧早就不读它们了**：`V12:47` 当年写下的理由是
--      `-- 计数列（列表页直接读，免连表 count）`；`#35`（PR #36）已把列表页改成读时算
--      （`KnowledgeBaseRepositoryAdapter#countsFor` 一条 SQL 四个子查询，按未软删文档算），
--      实体上的四个访问器在全 `main` 代码里**零调用**。
--   ② **写侧只剩"置 0"与"种子回填"**：`KnowledgeBase` 构造器把它们置 0，
--      没有第二条写路径 ⇒ 除了 `V900` 的示例数据，这一列的值永远是 0。
--   ③ 于是它**不是"暂时没用"，而是"承诺了一个不存在的真值"**：表结构看起来有计数、
--      实际永远是 0（或示例数据里的一次性回填），按它排序/筛选会静默错序 ——
--      这正是本项目最忌讳的那类静默错（`silent-failure`）。
--
-- ── 为什么是"删"而不是"补齐"（择一 A，2026-10-29 拍板）──────────────────────
--
--   补齐 = 写入侧同事务维护 + 存量回填 + 一条巡检断言（三个数必须与读时算一致），
--   代价远大于删列，而**收益为零**（读侧已经有一份正确读数、且是唯一读数）。
--   留着一列"看起来是真值"的数字，比删掉它更容易在下次被误用。
--
-- ── 本批只做一件事：删列 ────────────────────────────────────────────────────
--
--   ★ 不动读侧（`CountsPort#countsFor` 继续现算）、不动前端契约
--     （`frontend/src/api/knowledge.ts` 的 `documentCount/segmentCount/charCount`
--       是**读时算**的响应字段，与本表无关）；示例数据 `V900` 同批去掉写入。
--   ★ 不用 `cascade`：四列没有被任何视图 / 索引 / 约束引用（全仓 grep 已核）。
--
-- ── 判据（Issue #44 写的）──────────────────────────────────────────────────
--
--   ① 全库 grep 四个列名零命中（除 `V12` 的建表历史与本文件的删除语句）；
--   ② `mvn verify` 全绿（含 `knowledge` 的读时算用例：列表页计数仍等于真实行数）；
--   ③ 列表页/详情页的计数仍走 `countsFor`（本迁移不改任何 Java 读路径）。
--
-- ════════════════════════════════════════════════════════════════════════════

alter table kb_knowledge_base
  drop column document_count,
  drop column segment_count,
  drop column char_count,
  drop column has_vectorized_content;
