-- ════════════════════════════════════════════════════════════════════════════
-- knowledge 模块：kb_qa_pair 加「该条是否直接作答」+ 问句全文索引
-- ════════════════════════════════════════════════════════════════════════════
--
-- ★ 这一段把 V31 的「数据层留缝」真正接到检索侧（Issue #78 第二段）。
--   V31 文件头写下的判据 ③「断言检索链路现在不消费它」在这一批**被主动废止** ——
--   它当初存在的唯一理由是防止「留了数据层」被读成「已接入」；现在真的接入了，
--   那条断言要换成「接了，而且两种模式各自的行为都被钉住」。
--
-- ── ① direct_answer：这一条命中之后，是「仅供参考」还是「就是这个答案」 ──────
--
-- ★ 用户 2026-11-28 的裁定（原话）：「问答对就得作为直接回复进行回复，而不是
--   混合之后再取 top5 这样的」。所以同一张表里存在两种**截然不同**的用法：
--
--   false（默认）= 召回型：与向量 / 全文 / 实体 / 关系并列成一路候选，走 RRF 融合，
--                  命中后由生成模型写答案，问答对只是"这条更该被引用"的证据。
--   true         = 直答型：命中即**直接把 answer 当作回答**返回，不融合、不调模型。
--                  用于「这个问题的答案已经定稿，任何改写都是退步」的场景。
--
-- ★ 为什么默认是 false 而不是 true：
--   直答是**跳过生成**的强动作 —— 一旦判错（问句相似但并非同一个问题），用户会拿到
--   一个语气笃定、内容不对的答案，而且**没有任何模型或检索环节能纠正它**。
--   默认成 false 意味着"不勾这个框，问答对就只是个更好的候选"；要变成直答必须有人
--   显式勾选。把"默认值"设成更保守的那一侧，与 `V31` 里「密级 NOT NULL 且没有默认值」
--   是同一条思路：宁可插入时多一次确定的报错，也不要一个不会报警的越权。
--
-- ── ② question_tsv：问句要能被分词后匹配 ───────────────────────────────────
--
-- ★ 用 `chinese_zh`，与 `V19`（`kb_segment.content_tsv`）**同一个配置**。
--   不做第二套分词：问答对命中的判据是「用户这句话和标定的问法是不是同一句」，
--   而"怎么切词"这件事全平台只该有一个答案 —— 换配置会让"分段能搜到、问答对搜不到"
--   这种无法解释的现象出现。
--
-- ★ 为什么是生成列而不是服务层写入：问句可以被改名（`PATCH` 改 question），
--   生成列由 PostgreSQL 保证"question 变了 tsv 就跟着变"，服务层忘记同步的可能性为零。
--   代价是 `to_tsvector('chinese_zh', …)` 必须是 immutable —— 它是（`V19` 已经这么用了）。
--
-- ★ 为什么还要 GIN 索引：直答判定和召回判定都在**每次提问**时跑，
--   而问答对的量级会随会话沉淀增长（`origin = 'CONVERSATION'`）；没有索引时
--   它是一条对 `answer` 做全表扫描的查询，且这条查询在对话主链路上。
--
-- ── 没有做的事（刻意） ────────────────────────────────────────────────────
--
-- ★ 不加 `unique (kb_id, question)`：同一句问法在不同库里可以有不同答案
--   （这是多库并存的正常形态），加了约束会让「同样的问题、不同制度」直接导不进来。
-- ★ 不加 `question_tsv` 的 trigger：生成列已经覆盖，trigger 是同一件事的第二种写法。
-- ★ 不给 `direct_answer` 加"必须低于某密级"之类的约束：密级与是否直答是**正交**的，
--   高密级问答对同样可以直答（只是只对该密级可见的账号生效）。
--
-- 迁移号接在 `V118`（受控关系七类）之后 —— 全库八个模块目录共用一条版本号链，
-- 不能按模块各编各的（`V31` 文件头已写明这一点）。

-- ★ 直答默认关闭：见文件头 ①。`not null` + `default false` 是安全的，
--   因为"老数据没有这个选择"与"老数据选择不直答"在语义上完全一致。
alter table kb_qa_pair
  add column direct_answer boolean not null default false;

-- ★ 问句分词列（生成列，`chinese_zh` 与 V19 同一个配置）：见文件头 ②
alter table kb_qa_pair
  add column question_tsv tsvector generated always as (to_tsvector('chinese_zh', question)) stored;

-- 直答判定 / 召回判定都走这一个索引；partial 与 `idx_qa_pair_kb_classification` 同口径
create index idx_qa_pair_question_tsv on kb_qa_pair using gin (question_tsv)
  where deleted_at is null;

comment on column kb_qa_pair.direct_answer is
  '命中后是否直接作为回答返回（true = 跳过融合与生成；false = 作为一路候选参与 RRF）';

comment on column kb_qa_pair.question_tsv is
  '问句的分词结果（chinese_zh，与 kb_segment.content_tsv 同配置），供全文匹配用';
