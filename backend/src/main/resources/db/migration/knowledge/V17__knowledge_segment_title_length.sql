-- knowledge 模块：kb_segment.title 加余量（第 8 周 · 0.3.0 修复）
-- ════════════════════════════════════════════════════════════════════════════
--
-- ★ 真事故：`title` 原本是 `varchar(255)`，而分段标题的设计上限是 **256 字**
--   （`12 §3.4`：无标题块取首个句子截取 ≤256 字）—— 一个字符之差，
--   后果是「首段稍长的文档一上传就 value too long for type character varying(255)」，
--   整篇建档 500（用户看到的是「生成预览失败：服务内部错误」）。
--
-- ★ 两处一起修，缺一不可：
--   ① 域侧：`Segment.clampTitle` 把标题夹到设计上限（三处来源都被覆盖）；
--   ② 库侧：本迁移把列放宽到 512 —— 留出余量，将来把域上限调大时**不必再改库**。
--      列宽只比域上限大、不比它小，是这类"值对象有上限"的场景该有的关系。
--
-- ★ 不改 V15：已应用的迁移改动会让 Flyway 校验和失败，只能新增。
-- ════════════════════════════════════════════════════════════════════════════

alter table kb_segment
  alter column title type varchar(512);

comment on column kb_segment.title is
  '分段标题（12 §3.4）。★ 域侧上限 256 字（Segment.MAX_TITLE_LENGTH），列宽留余量到 512 —— 列宽绝不小于域上限，否则会变成插入失败';
