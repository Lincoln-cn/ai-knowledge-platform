--  V35 · 消息级赞踩（`feedback`）—— S3「赞/取消赞刷新后仍在」的载体
--
--  ★ 为什么必须是**列**而不是"另建一张表"：
--    · 冻结契约里它是 `ChatMessage.feedback`（`api/conversations.ts:31`，取值 `'UP' | 'DOWN' | null`）
--      ⇒ 它跟着消息一起返回，不存在"另一次查询"；
--    · 赞踩是**一条消息的一个属性**（不是一条独立事实）：一条消息最多一个赞或一个踩，
--      且"取消"= 回到 null。用一张 (message_id, type) 的表来表达"最多一条"，要多一条唯一约束
--      才能表达契约已经保证的事。
--  ★ 与 `#feedback` 域（`/feedbacks` 那族，反馈处理闭环）**不是一回事**：
--    那是一个**有状态机的业务流程**（待处理 / 处理中 / 已解决 + 指派 + 沉淀到知识库，属 V0.2），
--    而这里只是"用户对这条回答的评价"。两者共用一个词，但一张表、一个列就够。
--
--  ★ 与 `13 §12`（安全闸门）无关；与 `10 §7.4`（问答对）相关但**不是**它：
--    问答对（`kb_qa_pair`，V31）是"检索侧的确定性手段"，本列是"用户反馈"。
-- ══════════════════════════════════════════════════════════════════════════════

alter table cv_message
    add column feedback varchar(8);

-- ★ 取值域用 CHECK 而不是枚举类型：与 `cv_message.status`（见 V33）同一条做法 ——
--   本仓的枚举一律"应用层枚举 + 库层 CHECK"，不建 PG 类型（改枚举值要动 DDL 是另一回事）。
alter table cv_message
    add constraint chk_msg_feedback check (feedback is null or feedback in ('UP', 'DOWN'));

-- ★★ 只有**助手**消息能被赞踩：用户自己那条消息上的"赞"没有任何含义，
--    而它一旦被写进去，就会在界面上出现一个语义不成立的按钮。
--    ★ 用 CHECK + 子查询在 PG 里**做不到**（CHECK 不能引用别的列/行），所以这条约束
--      落在应用层（`Message#rate`），这里只把口径写进注释，避免下一个人以为库层兜住了。
comment on column cv_message.feedback is
  '消息级赞踩（契约 ChatMessage.feedback）。null = 未评价；UP/DOWN 互斥且可撤销（传 null 取消）。'
  '★ 取值域由 chk_msg_feedback 兜住；"只有助手消息可被评价"这条**在应用层**（Message#rate），'
  '因为 PG 的 CHECK 不能跨行引用。'
  '★ 与 /feedbacks 那族（反馈处理闭环，属 V0.2）不是一回事：那是有状态机的业务流程，这里只是评价。';
