package cn.lincoln.aiplatform.platform.compliance;

/**
 * 投诉举报工单的类别（{@code #83} 第十五条）。
 *
 * <p>投诉与举报分开两类是**受理口径**的需要：投诉 = 对本平台服务本身的不满， 举报 = 对平台内违法和不良信息的检举（对应第十四条的处置义务）。两类共用一套工单流转，
 * 但公示的「处理流程」对它们的措辞不同，落库时必须能分开统计。
 */
public enum ComplaintKind {
  /** 投诉：对平台服务的投诉（第十五条前半句）。 */
  COMPLAINT,
  /** 举报：对平台内违法和不良信息的检举（第十五条后半句，衔接第十四条处置义务）。 */
  REPORT
}
