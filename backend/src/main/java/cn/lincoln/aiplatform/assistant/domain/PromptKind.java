package cn.lincoln.aiplatform.assistant.domain;

/**
 * 提示词表（{@code as_prompt_config}）里两种用途的判别。
 *
 * <p>★ 为什么不是两张表：两类的字段几乎重合（名称 / 正文 / 分类 / 描述 / 图标），分开就是两套管理页、两套分类法、 两套权限点。差别只在「给谁看」，而那一点用一列就表达得完。
 *
 * <p>★ 这一列不能靠命名约定去猜（比如"问题结尾带问号就是提问模板"）：模板可以被改一个字就变成陈述句， 而它的用途不会因此改变。
 */
public enum PromptKind {

  /** 角色指令：给模型的身份设定。应用配置里选用后写进 {@code role_prompt}，终端用户看不到它。 */
  ROLE,

  /** 提问模板：给终端用户的问法示例。正文就是用户会看到的那句问题，出现在对话页空态与上弹抽屉里。 */
  QUESTION
}
