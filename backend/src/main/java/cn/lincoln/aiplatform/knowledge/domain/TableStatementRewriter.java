package cn.lincoln.aiplatform.knowledge.domain;

/**
 * 表格改写的<strong>接缝</strong>：把 GFM 表格改成「行级自包含陈述」（第 10 周 · 0.3.2 判据 ①②③）。
 *
 * <h3>为什么要改写</h3>
 *
 * <p>表格按原形进 {@code search_text} 时，<strong>一行的语义被"列头离得远"稀释了</strong>： 检索里那句「住宿标准是多少」与表格里那行 {@code |
 * 一线城市 | 500 | 元/天 |} 之间 没有任何共同的词面 —— 向量也难，全文更难。陈述化把每一行变成一句自包含的话 （{@code 住宿标准：一线城市 500
 * 元/天}），行与问题才在同一个语言平面上 （{@code 12 §4.3} 的 V1 条目，证据 D-RAC：输出 token ↓95.7%、成本 ↓77.8–85.6%）。
 *
 * <h3>★ 为什么"先规则、LLM 留口子"（用户拍板）</h3>
 *
 * <p>规则版：<strong>可表驱动单测、零模型调用、零成本、结果确定</strong> —— 先把它做扎实， 覆盖大多数"列头 + 值"的表。而**LLM
 * 版作为同一接口的第二个实现**接进来即可， <strong>接缝就是本接口</strong>（{@link Segmenter} 的构造函数接受任意实现，
 * 现有调用方走无参构造、默认用规则版，一行都不用改）。
 *
 * <p>★ LLM 版**现在不做**（不做半成品）：它的触发条件是 —— <em>命中测试里"表格类问题"的召回率明显低于其它问题</em>（用第 10 周的真栈闸门量），
 * 或<strong>规则版覆盖不到的表（多级表头、跨页续表、单位混排）占比超过阈值</em>。 记在 {@code docs/已知问题与欠账.md} 的待触发项里，不预写代码。
 *
 * <h3>★ 与判据 ③ 的关系（两列分工）</h3>
 *
 * <p>{@code content} 永远保留<strong>原表</strong>（引用展示要能溯源到用户看到的那张表）， 改写只作用于 {@code
 * search_text}。两个列由此<strong>必然不同</strong> —— 判据 ③ 的断言就是它。
 */
public interface TableStatementRewriter {

  /**
   * 把一段 GFM 表格改写成行级陈述（每行一句，用换行分隔）。
   *
   * <p>★ 不是表格就<strong>原样返回</strong>：调用方不必先判断类型（{@link Segmenter} 只在
   * 表格分段上调用它，但让实现自己也能安全处理非表格，省掉一层"调用方必须判断对"的约定）。
   */
  String rewrite(String markdown);
}
